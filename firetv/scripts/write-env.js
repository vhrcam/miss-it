// Writes src/env.ts from the repo's .env before each build, so the
// device key reaches the app without ever being committed.
const fs = require('fs');
const path = require('path');

const CLOUD_API_URL = 'https://2u2bgqgqomx6gewmpgctctbvp40izqpe.lambda-url.us-east-1.on.aws';

function readDotEnv(file) {
  if (!fs.existsSync(file)) {
    return {};
  }
  const pairs = fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .map(line => /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line))
    .filter(Boolean)
    .map(([, key, value]) => [key, value.replace(/^(['"])(.*)\1$/, '$2')]);
  return Object.fromEntries(pairs);
}

const fromFile = readDotEnv(path.resolve(__dirname, '../../.env'));
const read = key => process.env[key] || fromFile[key];
const quote = value => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const apiUrl = read('MISS_IT_API_URL') || CLOUD_API_URL;
const deviceKey = read('MISS_IT_DEVICE_KEY') || 'dev-device-key';
if (!read('MISS_IT_DEVICE_KEY')) {
  console.warn('MISS_IT_DEVICE_KEY is not set, so the app uses dev-device-key (local server only).');
}

fs.writeFileSync(
  path.resolve(__dirname, '../src/env.ts'),
  '// Generated by scripts/write-env.js from the repo .env. Not committed.\n/* eslint-disable prettier/prettier */\n\n' +
    `export const env = {\n  apiUrl: ${quote(apiUrl)},\n  deviceKey: ${quote(deviceKey)},\n};\n`,
);
console.log(`Wrote src/env.ts for ${apiUrl}`);
